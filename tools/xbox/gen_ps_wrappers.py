#!/usr/bin/env python3
"""Generates src/xbox/ps_wrappers.inc: one PSxxx(...) -> C_xxx(...) wrapper per SDK paired-single function that has
a C reference twin (the SDK ships both; the PS ones are PowerPC assembly and cannot run on the Xbox).

usage: tools/xbox/gen_ps_wrappers.py [--check]
"""
import glob, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'xbox', 'ps_wrappers.inc')
RET = r'(void|f32|u32|s32|BOOL)'


def decls(prefix, text):
    return {m.group(2): (m.group(1), m.group(3).strip())
            for m in re.finditer(r'^' + RET + r'\s+(' + prefix + r'(?:MTX|MTX44|VEC|QUAT)\w*)\(([^)]*)\);', text, re.M)}


def generate():
    text = ''
    for f in sorted(glob.glob(os.path.join(ROOT, 'include', 'dolphin', '**', '*.h'), recursive=True)):
        text += open(f).read() + '\n'
    ps, c = decls('PS', text), decls('C_', text)
    lines = ['// GENERATED by tools/xbox/gen_ps_wrappers.py. Do not edit.',
             '// Every SDK paired-single routine that has a C reference twin calls it (the PS versions are PowerPC assembly).']
    skipped = []
    for name in sorted(ps):
        twin = 'C_' + name[2:]
        if twin not in c or name == 'PSMTXReorder':
            skipped.append(name)
            continue
        ret, params = ps[name]
        args = [a.strip() for a in params.split(',')] if params and params != 'void' else []
        decl, call = [], []
        for i, a in enumerate(args):
            m = re.match(r'^(.*?)([A-Za-z_]\w*)$', a)
            ty = m.group(1).strip() if m and m.group(1).strip() else a
            if m and m.group(1).strip().endswith('*'):
                ty = m.group(1)
            decl.append('%s a%d' % (ty.rstrip(), i) if not ty.endswith('*') else '%sa%d' % (ty, i))
            call.append('a%d' % i)
        body = '%s(%s);' % (twin, ', '.join(call))
        lines.append('%s %s(%s) { %s%s }' % (ret, name, ', '.join(decl) or 'void', '' if ret == 'void' else 'return ', body))
    lines.append('// without a C twin (not wrapped): ' + ', '.join(skipped))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            sys.exit('ps_wrappers.inc is out of date; run tools/xbox/gen_ps_wrappers.py')
        print('ps_wrappers.inc is up to date')
    else:
        open(OUT, 'w').write(text)
        print('wrote', OUT, text.count('\n') - 3, 'wrappers')
