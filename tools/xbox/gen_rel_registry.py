#!/usr/bin/env python3
"""Generates src/xbox/rel_registry.cpp from config/G4BE08/modules/*/rel.json.

One entry per REL module: its module id (what OSLink finds in the REL header) and the three entry points,
which the Xbox build must give the unique names <module>_prolog / _epilog / _unresolved (compile the module
with -D_prolog=<module>_prolog -D_epilog=<module>_epilog -D_unresolved=<module>_unresolved).

usage: tools/xbox/gen_rel_registry.py [--check]     (--check: fail when the checked-in file is out of date)
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BASE = os.path.join(ROOT, 'config', 'G4BE08', 'modules')
OUT = os.path.join(ROOT, 'src', 'xbox', 'rel_registry.cpp')


def generate():
    mods = []
    for name in sorted(os.listdir(BASE)):
        p = os.path.join(BASE, name, 'rel.json')
        if os.path.isfile(p):
            with open(p) as f:
                mods.append((name, json.load(f)['module_id']))
    ids = [i for _, i in mods]
    assert len(set(ids)) == len(ids), 'duplicate module ids'
    lines = [
        '// GENERATED by tools/xbox/gen_rel_registry.py from config/G4BE08/modules/*/rel.json. Do not edit.',
        '#ifdef RE4_XBOX',
        '#include "xbox/xrel.h"',
        '',
        'extern "C" {',
    ]
    for n, _ in mods:
        lines.append('void %s_prolog(void); void %s_epilog(void); void %s_unresolved(void);' % (n, n, n))
    lines += ['}', '', 'static const XRelModule s_modules[] = {']
    for n, i in mods:
        lines.append('    {%d, "%s", %s_prolog, %s_epilog, %s_unresolved},' % (i, n, n, n, n))
    lines += ['};', '',
              'extern "C" void XRel_Init(void) { XRel_Register(s_modules, sizeof(s_modules) / sizeof(s_modules[0])); }',
              '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            sys.exit('rel_registry.cpp is out of date; run tools/xbox/gen_rel_registry.py')
        print('rel_registry.cpp is up to date')
    else:
        with open(OUT, 'w') as f:
            f.write(text)
        print('wrote', OUT, text.count('_prolog, '), 'modules')
